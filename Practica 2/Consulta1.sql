-- CONSULTA 1
-- Listado de todas las evaluaciones realizadas en el dia, parametro: fecha a consultar muestra datos generales del evaluado, notas y APROBADO/REPROBADO
-- (Aprobado = minimo 70 puntos teóricos Y 70 puntos prácticos)

SELECT
    R.ID_REGISTRO,
    R.NOMBRE_COMPLETO,
    R.GENERO,
    R.TIPO_TRAMITE,
    R.TIPO_LICENCIA,
    R.FECHA,
    D.NOMBRE        AS DEPARTAMENTO,
    M.NOMBRE        AS MUNICIPIO,
    E.NOMBRE        AS ESCUELA,
    C.NOMBRE        AS CENTRO,

    (
        SELECT COUNT(*) * 4
        FROM RESPUESTA_USUARIO RU
        JOIN PREGUNTAS P ON RU.PREGUNTA_ID_PREGUNTA = P.ID_PREGUNTA
        WHERE RU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
          AND RU.RESPUESTA = P.RESPUESTA
    ) AS NOTA_TEORICA,

    (
        SELECT SUM(RPU.NOTA)
        FROM RESPUESTA_PRACTICO_USUARIO RPU
        WHERE RPU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
    ) AS NOTA_PRACTICA,

    CASE
        WHEN (
            SELECT COUNT(*) * 4
            FROM RESPUESTA_USUARIO RU
            JOIN PREGUNTAS P ON RU.PREGUNTA_ID_PREGUNTA = P.ID_PREGUNTA
            WHERE RU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
              AND RU.RESPUESTA = P.RESPUESTA
        ) >= 70
        AND (
            SELECT SUM(RPU.NOTA)
            FROM RESPUESTA_PRACTICO_USUARIO RPU
            WHERE RPU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
        ) >= 70
        THEN 'APROBADO'
        ELSE 'REPROBADO'
    END AS RESULTADO

FROM EXAMEN EX
JOIN REGISTRO R     ON EX.REGISTRO_ID_REGISTRO                    = R.ID_REGISTRO
JOIN MUNICIPIO M    ON R.MUNICIPIO_ID_MUNICIPIO                   = M.ID_MUNICIPIO
                   AND R.MUNICIPIO_DEPARTAMENTO_ID_DEPARTAMENTO   = M.DEPARTAMENTO_ID_DEPARTAMENTO
JOIN DEPARTAMENTO D ON M.DEPARTAMENTO_ID_DEPARTAMENTO             = D.ID_DEPARTAMENTO
JOIN ESCUELA E      ON R.UBICACION_ESCUELA_ID_ESCUELA             = E.ID_ESCUELA
JOIN CENTRO C       ON R.UBICACION_CENTRO_ID_CENTRO               = C.ID_CENTRO

WHERE TRUNC(R.FECHA) = TO_DATE('13/03/2023', 'DD/MM/YYYY')

ORDER BY R.ID_REGISTRO;