-- En base a un rango de fechas, mostrar las notas de las evaluaciones considerando SOLO las evaluaciones APROBADAS.
-- (Aprobado = mínimo 70 puntos teóricos Y 70 puntos prácticos)

SELECT
    R.ID_REGISTRO,
    R.NOMBRE_COMPLETO,
    R.GENERO,
    R.TIPO_TRAMITE,
    R.TIPO_LICENCIA,
    R.FECHA,

    (
        SELECT COUNT(*) * 4
        FROM RESPUESTA_USUARIO RU
        JOIN PREGUNTAS P ON RU.PREGUNTA_ID_PREGUNTA = P.ID_PREGUNTA
        WHERE RU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
          AND RU.RESPUESTA = P.RESPUESTA
    ) AS NOTA_TEORICA,

    (
        SELECT SUM(RPU.NOTA)
        FROM RESPUESTA_PRACTICO_USUARIO RPU
        WHERE RPU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
    ) AS NOTA_PRACTICA

FROM EXAMEN EX
JOIN REGISTRO R ON EX.REGISTRO_ID_REGISTRO = R.ID_REGISTRO

WHERE (
    SELECT COUNT(*) * 4
    FROM RESPUESTA_USUARIO RU
    JOIN PREGUNTAS P ON RU.PREGUNTA_ID_PREGUNTA = P.ID_PREGUNTA
    WHERE RU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
      AND RU.RESPUESTA = P.RESPUESTA
) >= 70
AND (
    SELECT SUM(RPU.NOTA)
    FROM RESPUESTA_PRACTICO_USUARIO RPU
    WHERE RPU.EXAMEN_ID_EXAMEN = EX.ID_EXAMEN
) >= 70

AND TRUNC(R.FECHA) BETWEEN TO_DATE('01/01/2023', 'DD/MM/YYYY')
                       AND TO_DATE('31/12/2023', 'DD/MM/YYYY')

ORDER BY R.FECHA, R.ID_REGISTRO;