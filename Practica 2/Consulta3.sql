-- En base a un rango de fechas, mostrar cuantos registros de evaluaciones fueron realizadas por TIPO DE TRÁMITE y TIPO DE LICENCIA solicitada.

SELECT
    R.TIPO_TRAMITE,
    R.TIPO_LICENCIA,
    COUNT(*) AS TOTAL_EVALUACIONES

FROM EXAMEN EX
JOIN REGISTRO R ON EX.REGISTRO_ID_REGISTRO = R.ID_REGISTRO

WHERE TRUNC(R.FECHA) BETWEEN TO_DATE('01/01/2023', 'DD/MM/YYYY')
                         AND TO_DATE('31/12/2023', 'DD/MM/YYYY')

GROUP BY R.TIPO_TRAMITE, R.TIPO_LICENCIA
ORDER BY R.TIPO_TRAMITE, R.TIPO_LICENCIA;