-- CONSULTA 4
-- Listar las preguntas con MAYORES ACIERTOS en base a un rango de fechas.

SELECT
    P.ID_PREGUNTA,
    P.PREGUNTA_TEXTO,
    P.RES1,
    P.RES2,
    P.RES3,
    P.RES4,
    P.RESPUESTA                     AS OPCION_CORRECTA,
    COUNT(RU.ID_RESPUESTA_USUARIO)  AS TOTAL_ACIERTOS

FROM RESPUESTA_USUARIO RU
JOIN PREGUNTAS P  ON RU.PREGUNTA_ID_PREGUNTA = P.ID_PREGUNTA
JOIN EXAMEN EX    ON RU.EXAMEN_ID_EXAMEN     = EX.ID_EXAMEN
JOIN REGISTRO R   ON EX.REGISTRO_ID_REGISTRO = R.ID_REGISTRO

WHERE RU.RESPUESTA = P.RESPUESTA

AND TRUNC(R.FECHA) BETWEEN TO_DATE('01/01/2023', 'DD/MM/YYYY')
                       AND TO_DATE('31/12/2023', 'DD/MM/YYYY')

GROUP BY
    P.ID_PREGUNTA,
    P.PREGUNTA_TEXTO,
    P.RES1,
    P.RES2,
    P.RES3,
    P.RES4,
    P.RESPUESTA

ORDER BY TOTAL_ACIERTOS DESC;