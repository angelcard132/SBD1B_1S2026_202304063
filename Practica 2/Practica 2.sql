
-- 1. DEPARTAMENTO
CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO NUMBER PRIMARY KEY,
    NOMBRE          VARCHAR2(100) NOT NULL,
    CODIGO          NUMBER NOT NULL
);

-- 2. MUNICIPIO
CREATE TABLE MUNICIPIO (
    ID_MUNICIPIO                 NUMBER PRIMARY KEY,
    DEPARTAMENTO_ID_DEPARTAMENTO NUMBER NOT NULL,
    NOMBRE                       VARCHAR2(100) NOT NULL,
    CODIGO                       NUMBER NOT NULL,
    CONSTRAINT fk_municipio_depto FOREIGN KEY (DEPARTAMENTO_ID_DEPARTAMENTO)
        REFERENCES DEPARTAMENTO(ID_DEPARTAMENTO)
);

-- unique necesario para la foreignkey compuesta en REGISTRO
ALTER TABLE MUNICIPIO ADD CONSTRAINT uq_municipio_depto 
    UNIQUE (ID_MUNICIPIO, DEPARTAMENTO_ID_DEPARTAMENTO);

-- 3. CENTRO

CREATE TABLE CENTRO (
    ID_CENTRO NUMBER PRIMARY KEY,
    NOMBRE    VARCHAR2(100) NOT NULL
);

-- 4. ESCUELA
CREATE TABLE ESCUELA (
    ID_ESCUELA NUMBER PRIMARY KEY,
    NOMBRE     VARCHAR2(100) NOT NULL,
    DIRECCION  VARCHAR2(200),
    ACUERDO    VARCHAR2(50)
);


-- 5. UBICACION

CREATE TABLE UBICACION (
    ESCUELA_ID_ESCUELA NUMBER NOT NULL,
    CENTRO_ID_CENTRO   NUMBER NOT NULL,
    CONSTRAINT pk_ubicacion PRIMARY KEY (ESCUELA_ID_ESCUELA, CENTRO_ID_CENTRO),
    CONSTRAINT fk_ubic_escuela FOREIGN KEY (ESCUELA_ID_ESCUELA)
        REFERENCES ESCUELA(ID_ESCUELA),
    CONSTRAINT fk_ubic_centro FOREIGN KEY (CENTRO_ID_CENTRO)
        REFERENCES CENTRO(ID_CENTRO)
);

-- 6. REGISTRO
CREATE TABLE REGISTRO (
    ID_REGISTRO                            NUMBER PRIMARY KEY,
    UBICACION_ESCUELA_ID_ESCUELA           NUMBER NOT NULL,
    UBICACION_CENTRO_ID_CENTRO             NUMBER NOT NULL,
    MUNICIPIO_ID_MUNICIPIO                 NUMBER NOT NULL,
    MUNICIPIO_DEPARTAMENTO_ID_DEPARTAMENTO NUMBER NOT NULL,
    FECHA                                  DATE NOT NULL,
    TIPO_TRAMITE                           VARCHAR2(50),
    TIPO_LICENCIA                          VARCHAR2(10),
    NOMBRE_COMPLETO                        VARCHAR2(200),
    GENERO                                 CHAR(1),
    CONSTRAINT fk_reg_escuela FOREIGN KEY (UBICACION_ESCUELA_ID_ESCUELA)
        REFERENCES ESCUELA(ID_ESCUELA),
    CONSTRAINT fk_reg_centro FOREIGN KEY (UBICACION_CENTRO_ID_CENTRO)
        REFERENCES CENTRO(ID_CENTRO),
    CONSTRAINT fk_reg_municipio FOREIGN KEY (MUNICIPIO_ID_MUNICIPIO, MUNICIPIO_DEPARTAMENTO_ID_DEPARTAMENTO)
        REFERENCES MUNICIPIO(ID_MUNICIPIO, DEPARTAMENTO_ID_DEPARTAMENTO)
);

-- 7. CORRELATIVO
CREATE TABLE CORRELATIVO (
    ID_CORRELATIVO NUMBER PRIMARY KEY,
    FECHA          DATE NOT NULL,
    NO_EXAMEN      NUMBER NOT NULL
);

-- 8. EXAMEN
CREATE TABLE EXAMEN (
    ID_EXAMEN                                       NUMBER PRIMARY KEY,
    REGISTRO_ID_ESCUELA                             NUMBER NOT NULL,
    REGISTRO_ID_CENTRO                              NUMBER NOT NULL,
    REGISTRO_MUNICIPIO_ID_MUNICIPIO                 NUMBER NOT NULL,
    REGISTRO_MUNICIPIO_DEPARTAMENTO_ID_DEPARTAMENTO NUMBER NOT NULL,
    REGISTRO_ID_REGISTRO                            NUMBER NOT NULL,
    CORRELATIVO_ID_CORRELATIVO                      NUMBER NOT NULL,
    CONSTRAINT fk_examen_registro FOREIGN KEY (REGISTRO_ID_REGISTRO)
        REFERENCES REGISTRO(ID_REGISTRO),
    CONSTRAINT fk_examen_correlativo FOREIGN KEY (CORRELATIVO_ID_CORRELATIVO)
        REFERENCES CORRELATIVO(ID_CORRELATIVO)
);

-- 9. PREGUNTAS (teoricas)
CREATE TABLE PREGUNTAS (
    ID_PREGUNTA    NUMBER PRIMARY KEY,
    PREGUNTA_TEXTO VARCHAR2(500) NOT NULL,
    RESPUESTA      NUMBER NOT NULL,
    RES1           VARCHAR2(200),
    RES2           VARCHAR2(200),
    RES3           VARCHAR2(200),
    RES4           VARCHAR2(200)
);


-- 10. PREGUNTAS_PRACTICO
CREATE TABLE PREGUNTAS_PRACTICO (
    ID_PREGUNTA_PRACTICO NUMBER PRIMARY KEY,
    PREGUNTA_TEXTO       VARCHAR2(500) NOT NULL,
    PUNTEO               NUMBER NOT NULL
);

-- 11. RESPUESTA_USUARIO
CREATE TABLE RESPUESTA_USUARIO (
    ID_RESPUESTA_USUARIO NUMBER PRIMARY KEY,
    PREGUNTA_ID_PREGUNTA NUMBER NOT NULL,
    EXAMEN_ID_EXAMEN     NUMBER NOT NULL,
    RESPUESTA            NUMBER NOT NULL,
    CONSTRAINT fk_ru_pregunta FOREIGN KEY (PREGUNTA_ID_PREGUNTA)
        REFERENCES PREGUNTAS(ID_PREGUNTA),
    CONSTRAINT fk_ru_examen FOREIGN KEY (EXAMEN_ID_EXAMEN)
        REFERENCES EXAMEN(ID_EXAMEN)
);

-- 12. RESPUESTA_PRACTICO_USUARIO
CREATE TABLE RESPUESTA_PRACTICO_USUARIO (
    ID_RESPUESTA_PRACTICO                  NUMBER PRIMARY KEY,
    PREGUNTA_PRACTICO_ID_PREGUNTA_PRACTICO NUMBER NOT NULL,
    EXAMEN_ID_EXAMEN                       NUMBER NOT NULL,
    NOTA                                   NUMBER NOT NULL,
    CONSTRAINT fk_rpu_pregunta FOREIGN KEY (PREGUNTA_PRACTICO_ID_PREGUNTA_PRACTICO)
        REFERENCES PREGUNTAS_PRACTICO(ID_PREGUNTA_PRACTICO),
    CONSTRAINT fk_rpu_examen FOREIGN KEY (EXAMEN_ID_EXAMEN)
        REFERENCES EXAMEN(ID_EXAMEN)
);