const express = require('express');
const router = express.Router();
const oracledb = require('oracledb');
const { getConnection } = require('../db/connection');

router.get('/', async (req, res) => {
    let conn;
    try {
        conn = await getConnection();
        const result = await conn.execute(`SELECT * FROM CORRELATIVO ORDER BY ID_CORRELATIVO`, [], { outFormat: oracledb.OUT_FORMAT_OBJECT });
        res.json(result.rows);
    } catch (err) { res.status(500).json({ error: err.message });
    } finally { if (conn) await conn.close(); }
});

router.get('/:id', async (req, res) => {
    let conn;
    try {
        conn = await getConnection();
        const result = await conn.execute(`SELECT * FROM CORRELATIVO WHERE ID_CORRELATIVO = :id`, [req.params.id], { outFormat: oracledb.OUT_FORMAT_OBJECT });
        if (result.rows.length === 0) return res.status(404).json({ error: 'No encontrado' });
        res.json(result.rows[0]);
    } catch (err) { res.status(500).json({ error: err.message });
    } finally { if (conn) await conn.close(); }
});

router.post('/', async (req, res) => {
    let conn;
    const data = Array.isArray(req.body) ? req.body : [req.body];
    try {
        conn = await getConnection();
        const inserted = [];
        for (const item of data) {
            const result = await conn.execute(
                `INSERT INTO CORRELATIVO (ID_CORRELATIVO, FECHA, NO_EXAMEN)
                 VALUES (seq_correlativo.NEXTVAL, TO_DATE(:FECHA, 'YYYY-MM-DD'), :NO_EXAMEN)
                 RETURNING ID_CORRELATIVO INTO :id`,
                {
                    FECHA: item.FECHA,
                    NO_EXAMEN: item.NO_EXAMEN,
                    id: { type: oracledb.NUMBER, dir: oracledb.BIND_OUT }
                },
                { autoCommit: true }
            );
            inserted.push({ ID_CORRELATIVO: result.outBinds.id[0] });
        }
        res.status(201).json({ message: `${inserted.length} registro(s) creado(s)`, data: inserted });
    } catch (err) { res.status(500).json({ error: err.message });
    } finally { if (conn) await conn.close(); }
});

router.put('/:id', async (req, res) => {
    let conn;
    try {
        conn = await getConnection();
        await conn.execute(
            `UPDATE CORRELATIVO SET FECHA = TO_DATE(:FECHA, 'YYYY-MM-DD'), NO_EXAMEN = :NO_EXAMEN WHERE ID_CORRELATIVO = :id`,
            { FECHA: req.body.FECHA, NO_EXAMEN: req.body.NO_EXAMEN, id: req.params.id },
            { autoCommit: true }
        );
        res.json({ message: 'Correlativo actualizado' });
    } catch (err) { res.status(500).json({ error: err.message });
    } finally { if (conn) await conn.close(); }
});

router.delete('/:id', async (req, res) => {
    let conn;
    try {
        conn = await getConnection();
        await conn.execute(`DELETE FROM CORRELATIVO WHERE ID_CORRELATIVO = :id`, [req.params.id], { autoCommit: true });
        res.json({ message: 'Correlativo eliminado' });
    } catch (err) { res.status(500).json({ error: err.message });
    } finally { if (conn) await conn.close(); }
});

module.exports = router;